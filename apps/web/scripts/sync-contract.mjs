// Writes lib/generated/nameCredit.ts from the compiled contract and the mainnet deployment file, so the site
// can never drift from what was deployed. Run from apps/web after any contract build:  npm run sync
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = resolve(here, "..", "..", "..", "packages", "contracts");
const artifact = JSON.parse(readFileSync(resolve(contracts, "out", "NameCredit.sol", "NameCredit.json"), "utf8"));
const deployment = JSON.parse(readFileSync(resolve(contracts, "deployments", "56.json"), "utf8"));

const out = resolve(here, "..", "lib", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(
  resolve(out, "nameCredit.ts"),
  [
    "// Generated by scripts/sync-contract.mjs from the compiled contract and deployments/56.json. Do not edit.",
    `export const nameCreditAddress = "${deployment.nameCredit}" as const;`,
    `export const registryAddress = "${deployment.registry}" as const;`,
    `export const logsFromBlock = ${deployment.logsFromBlock}n;`,
    `export const nameCreditAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;`,
    "",
  ].join("\n"),
);
console.log(`wrote lib/generated/nameCredit.ts for ${deployment.nameCredit} with ${artifact.abi.length} ABI entries`);
